-- Практична робота 12. Сортування і фільтрація даних
-- Варіант: бібліотека. Використано наявні таблиці books, readers, loans.
-- Структура бази не змінюється: лише SELECT-запити.
-- Результати виконання кожного запиту наведені коментарями одразу після нього.

-- Завдання 1. ORDER BY за однією колонкою: найновіші позики першими.
SELECT id, book_id, reader_id, loan_date, return_date
FROM loans
ORDER BY loan_date DESC;
-- Результат:
-- (8, 3, None, '2026-10-17', None)
-- (6, 6, 2, '2026-10-10', '2026-10-18')
-- (5, 5, 5, '2026-10-08', None)
-- (4, 4, 4, '2026-10-06', '2026-10-20')
-- (3, 3, 3, '2026-10-04', None)
-- (2, 2, 2, '2026-10-02', '2026-10-12')
-- (1, 1, 1, '2026-10-01', '2026-11-01')

-- Завдання 2. ORDER BY за двома колонками:
-- спочатку читач (reader_id), у межах читача — дата позики від нової до старої.
SELECT id, reader_id, book_id, loan_date, return_date
FROM loans
ORDER BY reader_id ASC, loan_date DESC;
-- Результат:
-- (8, None, 3, '2026-10-17', None)
-- (1, 1, 1, '2026-10-01', '2026-11-01')
-- (6, 2, 6, '2026-10-10', '2026-10-18')
-- (2, 2, 2, '2026-10-02', '2026-10-12')
-- (3, 3, 3, '2026-10-04', None)
-- (4, 4, 4, '2026-10-06', '2026-10-20')
-- (5, 5, 5, '2026-10-08', None)

-- Завдання 3. Три найновіші позики.
SELECT id, book_id, reader_id, loan_date, return_date
FROM loans
ORDER BY loan_date DESC
LIMIT 3;
-- Результат:
-- (8, 3, None, '2026-10-17', None)
-- (6, 6, 2, '2026-10-10', '2026-10-18')
-- (5, 5, 5, '2026-10-08', None)

-- Завдання 4а. Унікальні жанри книжок.
SELECT DISTINCT genre
FROM books
ORDER BY genre;
-- Результат (6 унікальних значень):
-- ('Історична повість',)
-- ('Історичний роман',)
-- ('Драма',)
-- ('Повість',)
-- ('Поезія',)
-- ('Роман',)

-- Завдання 4б. Позики книжок з конкретним переліком ID.
-- IN доречний для окремих дискретних значень; BETWEEN задає суцільний діапазон.
SELECT id, book_id, reader_id, loan_date
FROM loans
WHERE book_id IN (1, 3, 5)
ORDER BY book_id, loan_date;
-- Результат:
-- (1, 1, 1, '2026-10-01')
-- (3, 3, 3, '2026-10-04')
-- (8, 3, None, '2026-10-17')
-- (5, 5, 5, '2026-10-08')

-- Завдання 5. Експеримент з LIKE на кириличному прізвищі.
-- Варіант з малої літери:
SELECT last_name
FROM readers
WHERE last_name LIKE 'к%'
ORDER BY last_name;
-- Результат (0 рядків):
-- (0 рядків)

-- Варіант з великої літери:
SELECT last_name
FROM readers
WHERE last_name LIKE 'К%'
ORDER BY last_name;
-- Результат (1 рядків):
-- ('Коваленко',)

-- Контроль: SQLite LIKE за замовчуванням нечутливий до регістру для ASCII,
-- але не виконує повноцінне Unicode case-folding для кирилиці.
